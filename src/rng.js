// Small seeded random number generator (mulberry32). Returns a function like Math.random: floats in [0, 1).
// Used by tests, headless sims and Line Tower Wars matches so a seed replays the same game.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
